from fastmcp import FastMCP
import os

# ------------------------------------------------------------------
# 1. MCP 서버 초기화 (기본 설정)
# ------------------------------------------------------------------
# 오류 방지를 위해 가장 기본적인 형태로 초기화합니다.
mcp = FastMCP("SafeMove Real Estate Agent")

# ------------------------------------------------------------------
# Tool 1: 부동산 등기부 리스크 분석
# ------------------------------------------------------------------
@mcp.tool()
async def analyze_registry_risk(address: str, owner_name: str) -> dict:
    """
    [부동산 리스크 진단] 다방/직방 매물 주소를 기반으로 등기부등본 및 건축물대장을 분석하여 깡통전세 위험을 진단합니다.
    """
    # 시뮬레이션: '위험', '빌라', '망원' 키워드가 있으면 경고
    if any(keyword in address for keyword in ["위험", "빌라", "망원"]):
        return {
            "status": "WARNING",
            "risk_score": 85,
            "summary": "🚨 깡통전세 위험 감지 (근저당 비율 80% 초과)",
            "details": {
                "registry": "선순위 근저당 설정 과다",
                "ownership": "최근 3개월 내 소유자 변경 이력 (주의)",
                "building": "위반 건축물 등재 여부: 없음"
            },
            "recommendation": [
                "전세보증금 반환보증(HUG/HF) 가입 필수",
                "특약사항: '잔금일 익일까지 권리변동 금지' 조항 추가"
            ]
        }

    return {
        "status": "SAFE",
        "risk_score": 10,
        "summary": "✅ 권리관계 안전 (근저당 없음)",
        "details": {
            "registry": "깨끗함 (말소사항 포함)",
            "ownership": "소유자 신원 일치",
            "building": "정상 건축물"
        },
        "recommendation": [
            "카카오뱅크 전세대출 한도 조회 및 금리 비교 추천",
            "확정일자 및 전입신고 즉시 진행"
        ]
    }

# ------------------------------------------------------------------
# Tool 2: 안전 계약 체크리스트 & 금융
# ------------------------------------------------------------------
@mcp.tool()
def safemove_checklist(contract_type: str) -> dict:
    """
    [체크리스트 & 금융] 계약 유형(전세/월세)에 따른 필수 확인 서류 및 카카오뱅크 대출 상품을 추천합니다.
    """
    base_checklist = [
        "공인중개사 정상 등록 여부 확인 (국가공간정보포털)",
        "임대인 신분증 진위 확인 (정부24)",
        "주택 임대차 표준계약서 사용"
    ]

    if contract_type == "전세":
        return {
            "type": "전세",
            "checklist": base_checklist + [
                "전세보증금 반환보증 가입 조건 확인",
                "국세/지방세 완납 증명서 확인",
                "계약서 특약 내 '독소조항' 유무 확인 (카카오 OCR)"
            ],
            "finance_guide": [
                "💰 카카오뱅크 HF 전월세보증금 대출 (최대 2.22억)",
                "💰 카카오뱅크 청년 전월세보증금 대출 (만 34세 이하, 90% 한도)"
            ]
        }
    
    return {
        "type": "월세",
        "checklist": base_checklist + [
            "관리비 세부 내역 확인 (전기/수도 포함 여부)",
            "소액임차인 최우선변제금 범위 확인"
        ],
        "finance_guide": [
            "💰 카카오뱅크 월세보증금 대출",
            "💰 비상금 대출 활용 가능"
        ]
    }

# ------------------------------------------------------------------
# 3. 서버 실행 (Railway 표준)
# ------------------------------------------------------------------
if __name__ == "__main__":
    # 0.0.0.0 호스트와 환경변수 PORT를 사용하여 외부 접속을 허용합니다.
    print("🚀 SafeMove Agent Starting...")
    mcp.run(
        transport="sse",
        host="0.0.0.0",
        port=int(os.environ.get("PORT", 8000))
    )
